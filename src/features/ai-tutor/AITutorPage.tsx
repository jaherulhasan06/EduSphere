import React, { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { Bot, Send, Sparkles, BookOpen, HelpCircle, CheckCircle2, RotateCcw } from 'lucide-react';
import { useEduSphere } from '../../contexts/EduSphereContext';
import { aiProvider } from '../../services/ai/MockAIProvider';
import { CLASS_LEVELS, getSubjectsForClass } from '../../constants/curriculum';
import { TutorMessage } from '../../types/edusphere';

const SUGGESTED_QUESTIONS = [
  {
    subject: 'Mathematics',
    topic: 'Quadratic Equations',
    question: 'How do I find the nature of roots using the discriminant D = b² - 4ac?'
  },
  {
    subject: 'Science (Combined)',
    topic: 'Electricity & Ohm’s Law',
    question: 'Explain Ohm’s Law and why stretching a wire to double its length makes resistance 4R.'
  },
  {
    subject: 'Biology / Science',
    topic: 'Photosynthesis & Vascular Transport',
    question: 'What are the main steps of photosynthesis and how do xylem and phloem differ?'
  },
  {
    subject: 'Mathematics',
    topic: 'Introduction to Trigonometry',
    question: 'How do I remember trigonometric ratios and prove sin²θ + cos²θ = 1?'
  }
];

export const AITutorPage: React.FC = () => {
  const { currentUser, boards } = useEduSphere();
  const [searchParams] = useSearchParams();

  const [classNumber, setClassNumber] = useState<number>(currentUser?.classNumber || 10);
  const [boardId, setBoardId] = useState<string>(currentUser?.boardId || 'CBSE');
  const [subject, setSubject] = useState<string>('Mathematics');
  const [topic, setTopic] = useState<string>(
    searchParams.get('topic') || 'Quadratic Equations'
  );
  const [inputMessage, setInputMessage] = useState<string>('');
  const [isGenerating, setIsGenerating] = useState<boolean>(false);
  const [error, setError] = useState<string | null>(null);

  const [messages, setMessages] = useState<TutorMessage[]>([]);

  const subjects = getSubjectsForClass(classNumber);

  useEffect(() => {
    const paramTopic = searchParams.get('topic');
    if (paramTopic) {
      setTopic(paramTopic);
    }
  }, [searchParams]);

  const handleSendMessage = async (customPrompt?: {
    subject?: string;
    topic?: string;
    question: string;
  }) => {
    const activeQuestion = customPrompt ? customPrompt.question : inputMessage;
    const activeSubject = customPrompt?.subject || subject;
    const activeTopic = customPrompt?.topic || topic;

    if (!activeQuestion.trim()) {
      setError('Please enter a question or select one of the suggested prompts below.');
      return;
    }

    setError(null);
    const userMsg: TutorMessage = {
      id: `msg-user-${Date.now()}`,
      sender: 'user',
      text: activeQuestion.trim(),
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
    };

    setMessages((prev) => [...prev, userMsg]);
    if (!customPrompt) setInputMessage('');
    setIsGenerating(true);

    try {
      const response = await aiProvider.generateTutorResponse({
        classNumber,
        boardId,
        subject: activeSubject,
        topic: activeTopic,
        userQuestion: activeQuestion
      });

      const aiMsg: TutorMessage = {
        id: `msg-ai-${Date.now()}`,
        sender: 'ai',
        structured: response,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      };

      setMessages((prev) => [...prev, aiMsg]);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to generate AI Tutor explanation.');
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Mandatory Demo AI Provider Notice */}
      <div className="p-4 rounded-xl bg-indigo-50/80 dark:bg-indigo-950/40 border border-indigo-200 dark:border-indigo-800/80 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2.5 text-xs font-medium text-indigo-900 dark:text-indigo-200">
          <Sparkles className="w-4 h-4 text-indigo-600 dark:text-indigo-400 shrink-0" />
          <span>
            Demo AI mode — responses are generated by a demonstration provider ({aiProvider.providerName}).
          </span>
        </div>
        <span className="text-[11px] text-indigo-700 dark:text-indigo-300 font-mono">
          Interface: AIProvider
        </span>
      </div>

      {/* Context Controls Bar */}
      <div className="p-5 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
          <div>
            <h1 className="text-xl font-bold font-display">Interactive AI Learning Tutor</h1>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Select your class, board, subject, and topic for structured step-by-step explanations.
            </p>
          </div>
          {messages.length > 0 && (
            <button
              onClick={() => setMessages([])}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 rounded-lg self-start"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>Clear Session</span>
            </button>
          )}
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
          <div>
            <label className="block text-[11px] font-semibold text-slate-500 mb-1">
              Class Level
            </label>
            <select
              value={classNumber}
              onChange={(e) => setClassNumber(Number(e.target.value))}
              className="w-full px-3 py-2 text-xs font-medium rounded-lg border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-950"
            >
              {CLASS_LEVELS.map((cls) => (
                <option key={cls} value={cls}>
                  Class {cls}
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="block text-[11px] font-semibold text-slate-500 mb-1">
              Education Board
            </label>
            <select
              value={boardId}
              onChange={(e) => setBoardId(e.target.value)}
              className="w-full px-3 py-2 text-xs font-medium rounded-lg border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-950"
            >
              {boards.map((b) => (
                <option key={b.id} value={b.id}>
                  {b.name}
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="block text-[11px] font-semibold text-slate-500 mb-1">
              Subject
            </label>
            <select
              value={subject}
              onChange={(e) => setSubject(e.target.value)}
              className="w-full px-3 py-2 text-xs font-medium rounded-lg border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-950"
            >
              {subjects.map((s) => (
                <option key={s} value={s}>
                  {s}
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="block text-[11px] font-semibold text-slate-500 mb-1">
              Chapter / Topic Focus
            </label>
            <input
              type="text"
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              placeholder="e.g. Quadratic Equations"
              className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-950"
            />
          </div>
        </div>
      </div>

      {/* Chat & Structured Explanation Viewport */}
      <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 flex flex-col min-h-[460px] justify-between space-y-6">
        {messages.length === 0 ? (
          <div className="my-auto py-8 text-center max-w-xl mx-auto space-y-5">
            <Bot className="w-10 h-10 text-indigo-600 dark:text-indigo-400 mx-auto" />
            <div className="space-y-1.5">
              <h2 className="text-lg font-bold font-display">
                Ask Any Concept or Numerical Question
              </h2>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Try one of these curriculum-aligned starter prompts or type your own question below:
              </p>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-left">
              {SUGGESTED_QUESTIONS.map((sq, index) => (
                <button
                  key={index}
                  onClick={() => {
                    setSubject(sq.subject);
                    setTopic(sq.topic);
                    handleSendMessage(sq);
                  }}
                  className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-950 hover:border-indigo-500 text-left space-y-1 transition-colors"
                >
                  <div className="text-[11px] font-semibold text-indigo-600 dark:text-indigo-400">
                    {sq.subject} · {sq.topic}
                  </div>
                  <div className="text-xs font-medium text-slate-800 dark:text-slate-200 line-clamp-2">
                    {sq.question}
                  </div>
                </button>
              ))}
            </div>
          </div>
        ) : (
          <div className="space-y-6 overflow-y-auto max-h-[540px] pr-1">
            {messages.map((msg) =>
              msg.sender === 'user' ? (
                <div key={msg.id} className="flex justify-end">
                  <div className="max-w-xl px-4 py-3 rounded-2xl bg-indigo-600 text-white text-sm space-y-1">
                    <p>{msg.text}</p>
                    <div className="text-[10px] text-indigo-200 text-right font-mono">
                      {msg.timestamp}
                    </div>
                  </div>
                </div>
              ) : (
                <div
                  key={msg.id}
                  className="p-5 rounded-2xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 space-y-4"
                >
                  <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
                    <div className="flex items-center gap-2">
                      <Bot className="w-4 h-4 text-indigo-600 dark:text-indigo-400" />
                      <span className="text-xs font-bold">
                        EduSphere AI Tutor · Class {msg.structured?.classNumber} ({boardId}) ·{' '}
                        {msg.structured?.subject}
                      </span>
                    </div>
                    <span className="text-[11px] text-slate-400 font-mono">
                      {msg.timestamp}
                    </span>
                  </div>

                  {msg.structured && (
                    <div className="space-y-4 text-sm">
                      {/* 1. Simple Explanation */}
                      <div className="space-y-1">
                        <div className="text-xs font-bold text-indigo-600 dark:text-indigo-400">
                          1. Simple Explanation
                        </div>
                        <p className="text-slate-700 dark:text-slate-300 leading-relaxed">
                          {msg.structured.simpleExplanation}
                        </p>
                      </div>

                      {/* 2. Step-by-Step Breakdown */}
                      <div className="space-y-1.5">
                        <div className="text-xs font-bold text-indigo-600 dark:text-indigo-400">
                          2. Step-by-Step Breakdown
                        </div>
                        <ol className="space-y-1.5 text-xs text-slate-700 dark:text-slate-300 list-decimal list-inside">
                          {msg.structured.stepByStepBreakdown.map((step, i) => (
                            <li key={i} className="leading-relaxed">
                              {step}
                            </li>
                          ))}
                        </ol>
                      </div>

                      {/* 3. Worked Example */}
                      <div className="p-3.5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 space-y-1">
                        <div className="text-xs font-bold text-emerald-700 dark:text-emerald-400">
                          3. Worked Example
                        </div>
                        <p className="text-xs text-slate-700 dark:text-slate-300 leading-relaxed font-mono">
                          {msg.structured.realWorldExample}
                        </p>
                      </div>

                      {/* 4. Important Points */}
                      <div className="space-y-1.5">
                        <div className="text-xs font-bold text-indigo-600 dark:text-indigo-400">
                          4. Important Board Exam Points
                        </div>
                        <ul className="space-y-1 text-xs text-slate-700 dark:text-slate-300">
                          {msg.structured.importantPoints.map((pt, i) => (
                            <li key={i} className="flex items-start gap-2">
                              <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0 mt-0.5" />
                              <span>{pt}</span>
                            </li>
                          ))}
                        </ul>
                      </div>

                      {/* 5. Follow-up Practice Question */}
                      <div className="p-3.5 rounded-xl bg-amber-50/70 dark:bg-amber-950/30 border border-amber-200/80 dark:border-amber-800/60 space-y-1">
                        <div className="flex items-center gap-1.5 text-xs font-bold text-amber-800 dark:text-amber-300">
                          <HelpCircle className="w-3.5 h-3.5" />
                          <span>5. Check Your Understanding (Follow-Up Practice)</span>
                        </div>
                        <p className="text-xs text-slate-800 dark:text-slate-200">
                          {msg.structured.followUpQuestion}
                        </p>
                      </div>
                    </div>
                  )}
                </div>
              )
            )}

            {isGenerating && (
              <div className="p-4 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 text-xs text-slate-500 animate-pulse">
                Generating structured Class {classNumber} ({boardId}) explanation...
              </div>
            )}
          </div>
        )}

        {/* Input Form */}
        <div className="pt-4 border-t border-slate-200 dark:border-slate-800 space-y-2">
          {error && <p className="text-xs text-rose-600 dark:text-rose-400">{error}</p>}
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="flex items-center gap-3"
          >
            <input
              type="text"
              value={inputMessage}
              onChange={(e) => setInputMessage(e.target.value)}
              placeholder={`Ask about ${topic} (${subject}, Class ${classNumber})...`}
              className="flex-1 px-4 py-2.5 text-sm rounded-xl border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-950"
            />
            <button
              type="submit"
              disabled={isGenerating}
              className="inline-flex items-center gap-2 px-5 py-2.5 text-sm font-semibold text-white bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 rounded-xl transition-colors whitespace-nowrap shrink-0"
            >
              <Send className="w-4 h-4" />
              <span>Ask Tutor</span>
            </button>
          </form>
        </div>
      </div>
    </div>
  );
};
